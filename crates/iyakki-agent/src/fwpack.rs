// ------------------------------------------------------------------------------------------------ the download

fn sha256_file(p: &Path) -> Result<String, String> {
    use sha2::{Digest, Sha256};
    let mut f = std::fs::File::open(p).map_err(|e| format!("{}: {e}", p.display()))?;
    let mut h = Sha256::new();
    let mut buf = vec![0u8; 64 * 1024];
    loop {
        let n = f.read(&mut buf).map_err(|e| format!("{}: {e}", p.display()))?;
        if n == 0 {
            break;
        }
        h.update(&buf[..n]);
    }
    Ok(h.finalize().iter().map(|b| format!("{b:02x}")).collect())
}

/// The hash of a file on disk (used by tests and the folder checks).
pub fn file_sha256(p: &Path) -> Result<String, String> {
    sha256_file(p)
}

fn host_ok(url: &str) -> bool {
    url.starts_with("https://") && crate::macrecovery::host_of(url).is_some_and(|h| HOSTS.iter().any(|a| h == *a || h.ends_with(&format!(".{a}"))))
}

/// Fetch `url` into `dest`, resuming from the bytes on disk, until it has `want` bytes. Only `https` addresses on [`HOSTS`] are used
/// (redirects included). A server that ignores the range and sends the whole file starts the file over; one that sends more than `want`
/// bytes is refused. The caller checks the SHA-256.
#[allow(clippy::too_many_arguments)]
pub fn fetch_resume(st: &dyn iyakki_proxy::Streamer, url: &str, want: u64, dest: &Path, retries: u32, pause: Duration, say: &mut dyn FnMut(&str), cancel: &dyn Fn() -> bool) -> Result<(), String> {
    if let Some(d) = dest.parent() {
        std::fs::create_dir_all(d).map_err(|e| format!("{}: {e}", d.display()))?;
    }
    let mut last_err = String::new();
    for attempt in 0..=retries {
        if attempt > 0 {
            std::thread::sleep(pause * attempt);
        }
        let mut have = std::fs::metadata(dest).map(|m| m.len()).unwrap_or(0);
        if have > want {
            let _ = std::fs::remove_file(dest);
            have = 0;
        }
        if have == want {
            return Ok(());
        }
        match fetch_once(st, url, want, dest, have, say, cancel) {
            Ok(()) => {
                let got = std::fs::metadata(dest).map(|m| m.len()).unwrap_or(0);
                if got == want {
                    return Ok(());
                }
                last_err = format!("got {got} of {want} bytes");
            }
            Err(Retry::Again(e)) => last_err = e,
            Err(Retry::Stop(e)) => return Err(e),
        }
    }
    Err(format!("the download of {url} did not finish: {last_err}"))
}

enum Retry {
    Again(String),
    Stop(String),
}

fn fetch_once(st: &dyn iyakki_proxy::Streamer, url: &str, want: u64, dest: &Path, have: u64, say: &mut dyn FnMut(&str), cancel: &dyn Fn() -> bool) -> Result<(), Retry> {
    let mut url = url.to_string();
    let mut head = None;
    for _ in 0..=5 {
        if !host_ok(&url) {
            return Err(Retry::Stop(format!("{url} is not an https address of git.kernel.org; refused")));
        }
        let mut h = vec![("User-Agent".to_string(), "IYAKKI".to_string()), ("Accept-Encoding".to_string(), "identity".to_string())];
        if have > 0 {
            h.push(("Range".to_string(), format!("bytes={have}-")));
        }
        let r = st.open(&url, &h).map_err(Retry::Again)?;
        if matches!(r.status, 301 | 302 | 303 | 307 | 308) {
            let loc = r.header("location").ok_or_else(|| Retry::Stop("a redirect without a place to go".into()))?.to_string();
            url = if loc.starts_with('/') {
                let rest = url.split_once("://").map_or("", |x| x.1);
                format!("https://{}{loc}", rest.split('/').next().unwrap_or(""))
            } else {
                loc
            };
            continue;
        }
        head = Some(r);
        break;
    }
    let mut head = head.ok_or_else(|| Retry::Stop("too many redirects".into()))?;
    let append = match head.status {
        206 => {
            let (from, _to, _total) = head.header("content-range").and_then(crate::macrecovery::parse_content_range).ok_or_else(|| Retry::Stop("the server answered a partial download without saying which part".into()))?;
            if from != have {
                return Err(Retry::Stop(format!("the server sent bytes from {from}, not from {have}")));
            }
            true
        }
        200 => false,
        416 => {
            let _ = std::fs::remove_file(dest);
            return Err(Retry::Again("the part on disk does not fit what the server has; starting over".into()));
        }
        403 | 404 => return Err(Retry::Stop(format!("the server refused the download (HTTP {}); the file may have moved", head.status))),
        s => return Err(Retry::Again(format!("HTTP {s}"))),
    };
    let mut file = if append {
        std::fs::OpenOptions::new().create(true).append(true).open(dest)
    } else {
        std::fs::OpenOptions::new().create(true).write(true).truncate(true).open(dest)
    }
    .map_err(|e| Retry::Stop(format!("{}: {e}", dest.display())))?;
    let mut done = if append { have } else { 0 };
    let mut buf = vec![0u8; 64 * 1024];
    let mut since = 0u64;
    loop {
        if cancel() {
            let _ = file.flush();
            return Err(Retry::Stop("stopped".into()));
        }
        match head.body.read(&mut buf) {
            Ok(0) => break,
            Ok(n) => {
                if done + n as u64 > want {
                    drop(file);
                    let _ = std::fs::remove_file(dest);
                    return Err(Retry::Stop(format!("the server sent more than the {want} bytes expected for {}; refused and deleted", dest.display())));
                }
                file.write_all(&buf[..n]).map_err(|e| Retry::Stop(format!("{}: {e} (is the disk full?)", dest.display())))?;
                done += n as u64;
                since += n as u64;
                if since >= 1 << 20 {
                    say(&format!("  {}: {} of {} KB", dest.file_name().map(|n| n.to_string_lossy().into_owned()).unwrap_or_default(), done >> 10, want >> 10));
                    since = 0;
                }
            }
            Err(e) => {
                let _ = file.flush();
                return Err(Retry::Again(format!("the connection dropped after {done} bytes: {e}")));
            }
        }
    }
    let _ = file.flush();
    Ok(())
}

// ------------------------------------------------------------------------------------------------ the real machine

pub struct RealEnv {
    pub data: PathBuf,
    pub streamer: std::sync::Arc<dyn iyakki_proxy::Streamer>,
    pub sys: PathBuf,
}

impl RealEnv {
    pub fn new(data: &Path, streamer: std::sync::Arc<dyn iyakki_proxy::Streamer>) -> RealEnv {
        RealEnv { data: data.to_path_buf(), streamer, sys: "/sys".into() }
    }
}

/// The state of a module under a `/sys` folder: a built-in module has `/sys/module/<name>` and no `initstate`.
pub fn module_state_in(sys: &Path, name: &str) -> ModState {
    let d = sys.join("module").join(name);
    if !d.is_dir() {
        ModState::Absent
    } else if d.join("initstate").exists() {
        ModState::Loaded
    } else {
        ModState::Builtin
    }
}

impl Env for RealEnv {
    fn say(&mut self, line: &str) {
        let mut o = std::io::stdout();
        let _ = writeln!(o, "{line}");
        let _ = o.flush();
    }
    fn hardware_present(&self, def: &Def) -> bool {
        present_in(&self.sys, def)
    }
    fn free_bytes(&self, dir: &Path) -> Option<u64> {
        crate::k3sdev::space(dir).map(|s| s.0)
    }
    fn data_in_memory(&self) -> bool {
        crate::macfw::in_memory(&std::fs::read_to_string("/proc/mounts").unwrap_or_default(), &self.data)
    }
    fn fetch(&mut self, url: &str, want: u64, dest: &Path) -> Result<(), String> {
        let st = self.streamer.clone();
        fetch_resume(&*st, url, want, dest, 5, Duration::from_secs(3), &mut |l| self.say(l), &|| false)
    }
    fn install(&mut self, def: &Def, version: &str, source: &str, p: &pack::Pack) -> Result<apply::Report, String> {
        let (fs, real) = apply::Fs::for_data(&self.data);
        let run: Box<dyn iyakki_drivers::run::Runner> = if real { Box::new(iyakki_drivers::run::System) } else { Box::new(iyakki_drivers::run::Dry) };
        apply::install_pack(&fs, run.as_ref(), def.pack_id, version, def.licence_id, source, "local", p)
    }
    fn module_state(&self, name: &str) -> ModState {
        module_state_in(&self.sys, name)
    }
    fn device_bound(&self, def: &Def) -> Option<bool> {
        bound_in(&self.sys, def)
    }
    fn now(&self) -> i64 {
        crate::clock::now_unix()
    }
}

