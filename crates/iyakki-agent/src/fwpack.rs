// ------------------------------------------------------------------------------------------------ the table

#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Entry {
    pub path: String,
    pub size: u64,
    pub sha256: String,
}

#[derive(Clone, Debug, PartialEq, Eq, Default)]
pub struct PackFiles {
    pub id: String,
    /// Licence texts (they travel with the files).
    pub docs: Vec<Entry>,
    pub files: Vec<Entry>,
}

#[derive(Clone, Debug, PartialEq, Eq, Default)]
pub struct Table {
    pub commit: String,
    pub base: String,
    pub packs: Vec<PackFiles>,
}

impl Table {
    pub fn pack(&self, id: &str) -> Option<&PackFiles> {
        self.packs.iter().find(|p| p.id == id)
    }

    /// The address of a file at the pinned commit.
    pub fn url(&self, path: &str) -> String {
        format!("{}/{}?id={}", self.base, path, self.commit)
    }
}

fn valid_hex(s: &str, n: usize) -> bool {
    s.len() == n && s.bytes().all(|b| b.is_ascii_digit() || (b'a'..=b'f').contains(&b))
}

/// Read a table text. Strict: a malformed line is an error (a bad pin must never be half used).
pub fn parse_table(text: &str) -> Result<Table, String> {
    let mut t = Table::default();
    for (n, line) in text.lines().enumerate() {
        let line = line.trim();
        if line.is_empty() || line.starts_with('#') {
            continue;
        }
        let w: Vec<&str> = line.split_whitespace().collect();
        let bad = |why: &str| format!("restricted-firmware table, line {}: {why}", n + 1);
        match w.as_slice() {
            ["commit", c] if valid_hex(c, 40) => t.commit = c.to_string(),
            ["base", b] if b.starts_with("https://") => t.base = b.trim_end_matches('/').to_string(),
            ["pack", id] if pack::valid_module_name(id) => t.packs.push(PackFiles { id: id.to_string(), ..Default::default() }),
            [kind @ ("doc" | "file"), size, sha, path] => {
                let size: u64 = size.parse().map_err(|_| bad("the size is not a number"))?;
                if !valid_hex(sha, 64) || size == 0 || !pack::safe_rel_path(path) {
                    return Err(bad("a size, a sha256 or a path is not valid"));
                }
                let p = t.packs.last_mut().ok_or_else(|| bad("a file before any pack"))?;
                let e = Entry { path: path.to_string(), size, sha256: sha.to_string() };
                if *kind == "doc" { p.docs.push(e) } else { p.files.push(e) }
            }
            _ => return Err(bad("not understood")),
        }
    }
    if t.commit.is_empty() || t.base.is_empty() || t.packs.is_empty() || t.packs.iter().any(|p| p.files.is_empty() || p.docs.is_empty()) {
        return Err("restricted-firmware table: a commit, a base address, and for every pack its files and licence texts are required".into());
    }
    Ok(t)
}

/// The built-in table (checked at first use; the tests check it too).
pub fn table() -> &'static Table {
    static T: OnceLock<Table> = OnceLock::new();
    T.get_or_init(|| parse_table(TABLE).expect("the pinned firmware table is valid"))
}

