//! Restricted firmware packs: firmware whose licence IYAKKI is not sure it may redistribute is **not in the images it publishes**. The
//! person installs it themselves, at their click, from the upstream linux-firmware repository (this module), or builds an image for their
//! own use that includes it (`IYAKKI_INCLUDE_RESTRICTED_FIRMWARE=1`, `docs/RESTRICTED-FIRMWARE.md`). Policy: `LICENSING.md` item 7 and
//! `docs/FIRMWARE-LICENCES.md` ("when in doubt it is not shipped; the user installs it").
//!
//! One detached job per pack (`iyakki quick-install fw-qualcomm-bt|fw-realtek-net|fw-broadcom-net|fw-atheros-carl9170`), the pattern of
//! `camfw.rs`:
//!
//! 1. the matching hardware must be present (PCI or USB ids, [`Def::hw`]) and the licence must have been accepted ([`accept`]: a record on
//!    the data volume, written by the Setup tile after the person ticked "I accept" and noted in the audit log, or by `--accept-licence`
//!    on the command line); otherwise nothing is downloaded or installed;
//! 2. every file and the vendor's licence texts are fetched over https from a **pinned commit** of the linux-firmware repository
//!    (`git.kernel.org`), resumable, each checked for size and SHA-256 against [`TABLE`] (the table is generated by
//!    `dist/release/pin-firmware.sh`; the image recipe reads the same file). One wrong byte and nothing is installed;
//! 3. the files become the driver pack `fw-<name>` on the data volume (`apply::install_pack`: linked into `/lib/firmware` at every boot, so it
//!    survives restarts and in-place stick updates; the licence texts are kept with the files), the driver is loaded again, and the job
//!    decides whether a restart is needed (a driver built into the kernel, or a device with no driver bound): "Reboot to finish". Nothing
//!    ever restarts the machine by itself.
//!
//! The offline route ([`run_folder`]) takes a folder or USB stick that holds the files (made on another computer with
//! `restricted-firmware.sh fetch`), checks the same table and installs the same way.
//!
//! The world is reached only through [`Env`]; the tests give it a fake (no network, no devices).

