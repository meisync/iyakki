/// A driver module as the kernel shows it.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum ModState {
    Absent,
    Loaded,
    /// Built into the kernel: it reads firmware only when it probes a device, at start.
    Builtin,
}

/// Everything the job does to the world.
pub trait Env {
    fn say(&mut self, line: &str);
    fn hardware_present(&self, def: &Def) -> bool;
    fn free_bytes(&self, dir: &Path) -> Option<u64>;
    fn data_in_memory(&self) -> bool;
    /// Fetch `url` into `dest`, resuming the bytes already there; `want` is the size it must have. The caller checks the SHA-256.
    fn fetch(&mut self, url: &str, want: u64, dest: &Path) -> Result<(), String>;
    fn install(&mut self, def: &Def, version: &str, source: &str, p: &pack::Pack) -> Result<apply::Report, String>;
    fn module_state(&self, name: &str) -> ModState;
    /// `Some(false)`: a device of the pack is there and no driver is bound to it.
    fn device_bound(&self, def: &Def) -> Option<bool>;
    fn now(&self) -> i64;
}

/// The plain result of a run, also written to `last.json`.
#[derive(Clone, Debug, Default, PartialEq, Eq, serde::Serialize, serde::Deserialize)]
#[serde(default)]
pub struct Outcome {
    pub at: i64,
    pub installed: bool,
    pub files: usize,
    /// "download" or "folder".
    pub source: String,
    pub reboot_needed: bool,
    pub headline: String,
    pub lines: Vec<String>,
}

pub fn read_outcome(data: &Path, def: &Def) -> Option<Outcome> {
    serde_json::from_str(&std::fs::read_to_string(result_path(data, def)).ok()?).ok()
}

fn write_outcome(data: &Path, def: &Def, o: &Outcome) {
    let _ = std::fs::create_dir_all(work_dir(data, def));
    let _ = std::fs::write(result_path(data, def), serde_json::to_string_pretty(o).unwrap_or_default());
}

/// A restart is still wanted: the run said so and the machine has not started since (`uptime` in seconds).
pub fn reboot_pending(o: &Outcome, now: i64, uptime: i64) -> bool {
    o.installed && o.reboot_needed && o.at > now - uptime
}

fn download_dir(data: &Path, def: &Def) -> PathBuf {
    work_dir(data, def).join("download")
}

/// Bytes kept between runs (the downloaded files).
pub fn leftovers(data: &Path, def: &Def) -> u64 {
    fn walk(d: &Path) -> u64 {
        std::fs::read_dir(d).into_iter().flatten().flatten().map(|e| match e.metadata() {
            Ok(m) if m.is_dir() => walk(&e.path()),
            Ok(m) => m.len(),
            Err(_) => 0,
        }).sum()
    }
    walk(&download_dir(data, def))
}

pub fn delete_leftovers(data: &Path, def: &Def) -> u64 {
    let n = leftovers(data, def);
    let _ = std::fs::remove_dir_all(download_dir(data, def));
    n
}

fn note(env: &mut dyn Env, lines: &mut Vec<String>, l: String) {
    env.say(&l);
    lines.push(l);
}

fn version_for(commit: &str) -> String {
    format!("linux-firmware {}", &commit[..commit.len().min(10)])
}

/// The pack made of verified files and the licence texts (kept under `licences/<pack>/` next to the files).
pub fn build_pack(t: &Table, def: &Def, files: &[(String, Vec<u8>)], docs: &[(String, Vec<u8>)]) -> pack::Pack {
    let mut p = pack::Pack { v: 1, why: format!("{} {} Not part of any IYAKKI image: installed on the person's request from linux-firmware commit {}.", def.about, def.vendor, &t.commit[..10]), reload: def.reload.iter().map(|s| s.to_string()).collect(), ..Default::default() };
    for (path, bytes) in files {
        p.files.push(pack::FwFile { path: path.clone(), data: b64::encode(bytes), sha256: sha256_hex(bytes) });
    }
    for (path, bytes) in docs {
        p.files.push(pack::FwFile { path: format!("licences/{}/{}", def.pack_id, path.replace('/', "-")), data: b64::encode(bytes), sha256: sha256_hex(bytes) });
    }
    p
}

/// Run the job (download route). `force_hardware` skips the hardware check (command line only). Returns the outcome (already written to `last.json`).
pub fn run(env: &mut dyn Env, data: &Path, def: &Def, force_hardware: bool) -> Result<Outcome, String> {
    run_with(env, table(), data, def, force_hardware, None)
}

/// Run the job from a folder or stick (offline route).
pub fn run_folder(env: &mut dyn Env, data: &Path, def: &Def, force_hardware: bool, dir: &Path) -> Result<Outcome, String> {
    run_with(env, table(), data, def, force_hardware, Some(dir))
}

/// The job against a given table (the tests use a small one with files they can make).
pub fn run_with(env: &mut dyn Env, t: &Table, data: &Path, def: &Def, force: bool, from: Option<&Path>) -> Result<Outcome, String> {
    let mut lines: Vec<String> = Vec::new();
    match run_inner(env, t, data, def, force, from, &mut lines) {
        Ok(o) => Ok(o),
        Err(e) => {
            let kept = leftovers(data, def);
            if kept > 0 {
                lines.push(format!("kept for a retry: {} KB in {} (the tile has Delete download)", kept >> 10, download_dir(data, def).display()));
            }
            let o = Outcome { at: env.now(), headline: format!("Not done: {e}"), lines, source: if from.is_some() { "folder".into() } else { "download".into() }, ..Default::default() };
            write_outcome(data, def, &o);
            Err(e)
        }
    }
}

fn check_entry(e: &Entry, bytes: &[u8]) -> Result<(), String> {
    if bytes.len() as u64 != e.size {
        return Err(format!("{} has {} bytes, not the expected {}", e.path, bytes.len(), e.size));
    }
    let got = sha256_hex(bytes);
    if got != e.sha256 {
        return Err(format!("{} has sha256 {got}, not the expected {}", e.path, e.sha256));
    }
    Ok(())
}

fn run_inner(env: &mut dyn Env, t: &Table, data: &Path, def: &Def, force: bool, from: Option<&Path>, lines: &mut Vec<String>) -> Result<Outcome, String> {
    let pf = t.pack(def.table_id).ok_or("this pack is not in the pinned table")?;
    note(env, lines, format!("[0/5] {} {NOTICE}", def.title));
    if !force && !env.hardware_present(def) {
        return Err(format!("no hardware of this pack ({}) was found on this computer; nothing was downloaded", def.about));
    }
    let Some(acc) = accepted_in(t, data, def) else {
        return Err(format!("the licence was not accepted: {} Nothing was downloaded or installed. Accept it on the tile (Store, Setup, Hardware) or with --accept-licence", def.licence_note));
    };
    note(env, lines, format!("licence accepted by {} (texts: {}; sha256 of the list {})", acc.by, pf.docs.iter().map(|d| d.path.as_str()).collect::<Vec<_>>().join(", "), &acc.licence_sha256[..16]));
    if env.data_in_memory() {
        return Err("the data volume is in memory (a live session): the firmware would be gone after a restart. Start from the installed system".into());
    }
    let dl = download_dir(data, def);
    std::fs::create_dir_all(&dl).map_err(|e| format!("{}: {e}", dl.display()))?;
    match env.free_bytes(data) {
        Some(f) if f < NEEDED_FREE => return Err(format!("the data volume has {} MB free; this needs about {} MB", f >> 20, NEEDED_FREE >> 20)),
        Some(f) => note(env, lines, format!("free space on the data volume: {} MB", f >> 20)),
        None => note(env, lines, "note: the free space of the data volume could not be read".into()),
    }

    // 1. get the bytes, every file checked against the pinned size and sha256
    let mut files: Vec<(String, Vec<u8>)> = Vec::new();
    let mut docs: Vec<(String, Vec<u8>)> = Vec::new();
    match from {
        None => {
            note(env, lines, format!("[1/5] downloading {} file(s) and {} licence text(s) ({} KB) from the linux-firmware repository, commit {}. A stopped download resumes", pf.files.len(), pf.docs.len(), (pf.files.iter().chain(&pf.docs).map(|e| e.size).sum::<u64>()) >> 10, &t.commit[..10]));
            for (is_doc, e) in pf.docs.iter().map(|e| (true, e)).chain(pf.files.iter().map(|e| (false, e))) {
                let dest = dl.join(&e.path);
                if let Some(d) = dest.parent() {
                    std::fs::create_dir_all(d).map_err(|er| format!("{}: {er}", d.display()))?;
                }
                env.fetch(&t.url(&e.path), e.size, &dest)?;
                let bytes = std::fs::read(&dest).map_err(|er| format!("{}: {er}", dest.display()))?;
                if let Err(er) = check_entry(e, &bytes) {
                    let _ = std::fs::remove_file(&dest);
                    return Err(format!("{er}. The file was deleted; the upstream file may have changed or the download was damaged. Nothing was installed"));
                }
                if is_doc { docs.push((e.path.clone(), bytes)) } else { files.push((e.path.clone(), bytes)) }
            }
            note(env, lines, format!("  all {} downloaded files match the pinned checksums", files.len() + docs.len()));
        }
        Some(dir) => {
            note(env, lines, format!("[1/5] reading the files from {}", dir.display()));
            let find = |e: &Entry| -> Option<PathBuf> {
                let base = Path::new(&e.path).file_name()?;
                [dir.join(&e.path), dir.join(base), dir.join("linux-firmware").join(&e.path), dir.join("firmware").join(&e.path)].into_iter().find(|p| p.is_file())
            };
            for e in &pf.files {
                if let Some(p) = find(e) {
                    let bytes = std::fs::read(&p).map_err(|er| format!("{}: {er}", p.display()))?;
                    check_entry(e, &bytes).map_err(|er| format!("{}: {er}. Nothing was installed (only the exact files of the pinned linux-firmware release are accepted)", p.display()))?;
                    files.push((e.path.clone(), bytes));
                }
            }
            if files.is_empty() {
                return Err(format!("none of the {} files of this pack is in {}; nothing was installed. Make the folder with restricted-firmware.sh fetch on a computer that has network", pf.files.len(), dir.display()));
            }
            for e in &pf.docs {
                if let Some(p) = find(e) {
                    let bytes = std::fs::read(&p).map_err(|er| format!("{}: {er}", p.display()))?;
                    check_entry(e, &bytes).map_err(|er| format!("{}: {er}. Nothing was installed", p.display()))?;
                    docs.push((e.path.clone(), bytes));
                }
            }
            note(env, lines, format!("  {} of {} files found and checked; the rest is not needed or not on the stick", files.len(), pf.files.len()));
            if docs.len() < pf.docs.len() {
                note(env, lines, format!("  note: {} licence text(s) were not in the folder; the texts are named in the pinned table ({}) and stay on the vendor's repository", pf.docs.len() - docs.len(), pf.docs.iter().map(|d| d.path.as_str()).collect::<Vec<_>>().join(", ")));
            }
        }
    }

    // 2. install as a driver pack, load the driver again
    note(env, lines, "[2/5] installing as a driver pack on the data volume (linked into /lib/firmware at every start)".into());
    let p = build_pack(t, def, &files, &docs);
    let source = if from.is_some() { format!("a folder, files checked against linux-firmware commit {}", t.commit) } else { format!("linux-firmware commit {} (git.kernel.org), downloaded on request", t.commit) };
    let rep = env.install(def, &version_for(&t.commit), &source, &p)?;
    for l in &rep.lines {
        note(env, lines, format!("  {l}"));
    }
    let _ = std::fs::remove_dir_all(&dl);

    // 3. does the machine need a restart?
    note(env, lines, "[3/5] checking whether the driver picked the files up".into());
    let mut why: Vec<String> = Vec::new();
    for m in def.reload {
        if env.module_state(m) == ModState::Builtin {
            why.push(format!("{m} is built into the kernel and reads its firmware only at start"));
        }
    }
    if rep.lines.iter().any(|l| l.contains("did not load")) {
        why.push("a driver did not load again".into());
    }
    if env.device_bound(def) == Some(false) {
        why.push("the device has no driver bound yet".into());
    }
    note(env, lines, "[4/5] writing the result".into());
    let reboot = !why.is_empty();
    let headline = if reboot { format!("{} installed. Reboot to finish.", def.title) } else { format!("{} installed and the driver was loaded again.", def.title) };
    let mut all = lines.clone();
    for w in &why {
        all.push(format!("restart wanted: {w}"));
    }
    let o = Outcome { at: env.now(), installed: true, files: files.len(), source: if from.is_some() { "folder".into() } else { "download".into() }, reboot_needed: reboot, headline, lines: all };
    write_outcome(data, def, &o);
    env.say(&format!("[5/5] done: {}", o.headline));
    Ok(o)
}

