/// The pinned table (`dist/release/pin-firmware.sh` writes it; `dist/buildroot/board/iyakki/restricted-firmware.sh` reads it too).
pub const TABLE: &str = include_str!("../../../dist/buildroot/board/iyakki/restricted-firmware.table");

