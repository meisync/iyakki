//! Third-party notices and a CycloneDX SBOM, both written here from the same data the gate checks (Cargo lock files with the licences
//! the crates state, `legal/assets.txt`, `legal/downloads.txt`, and the packages of a scanned image). Output is deterministic (no
//! timestamps, sorted) so the committed copies can be compared with a fresh run.

use std::collections::BTreeMap;

use crate::assets::AssetRow;
use crate::downloads;
use crate::sbom::Pkg;
use crate::spdx::{self, Class};

fn esc(s: &str) -> String {
    let mut o = String::new();
    for c in s.chars() {
        match c {
            '"' => o.push_str("\\\""),
            '\\' => o.push_str("\\\\"),
            '\n' => o.push_str("\\n"),
            c if (c as u32) < 0x20 => o.push(' '),
            c => o.push(c),
        }
    }
    o
}

fn purl(p: &Pkg) -> String {
    let ty = if p.origin.starts_with("cargo:") { "cargo" } else { "generic" };
    format!("pkg:{ty}/{}@{}", p.name, p.version)
}

fn lic_json(l: &str) -> String {
    if l.is_empty() {
        return "[]".into();
    }
    // a valid SPDX expression goes as an expression; Buildroot's free-text lists go as a name
    if !l.contains(',') && !l.contains(" (") && !l.contains('/') && spdx::parse(l).is_ok() && !l.to_lowercase().contains("public domain") && !l.contains("with advertising") {
        format!("[{{ \"expression\": \"{}\" }}]", esc(l))
    } else {
        format!("[{{ \"license\": {{ \"name\": \"{}\" }} }}]", esc(l))
    }
}

/// CycloneDX 1.5. `pkgs` are the code packages (Cargo and Buildroot), `assets` the artwork and data files of the repository.
pub fn cyclonedx(name: &str, version: &str, pkgs: &[Pkg], assets: &[AssetRow]) -> String {
    let mut seen = std::collections::BTreeSet::new();
    let mut comps: Vec<String> = Vec::new();
    let mut sorted: Vec<&Pkg> = pkgs.iter().collect();
    sorted.sort_by(|a, b| (&a.name, &a.version, &a.origin).cmp(&(&b.name, &b.version, &b.origin)));
    for p in sorted {
        if !seen.insert((p.name.clone(), p.version.clone(), p.origin.starts_with("cargo:"))) {
            continue;
        }
        let mut c = format!("    {{ \"type\": \"library\", \"bom-ref\": \"{}\", \"name\": \"{}\", \"version\": \"{}\", \"purl\": \"{}\", \"licenses\": {}", esc(&purl(p)), esc(&p.name), esc(&p.version), esc(&purl(p)), lic_json(&p.license));
        if !p.sha256.is_empty() {
            c.push_str(&format!(", \"hashes\": [{{ \"alg\": \"SHA-256\", \"content\": \"{}\" }}]", esc(&p.sha256)));
        }
        if p.source.starts_with("http") {
            c.push_str(&format!(", \"externalReferences\": [{{ \"type\": \"website\", \"url\": \"{}\" }}]", esc(&p.source)));
        }
        c.push_str(&format!(", \"properties\": [{{ \"name\": \"iyakki:origin\", \"value\": \"{}\" }}] }}", esc(&p.origin)));
        comps.push(c);
    }
    for a in assets {
        comps.push(format!("    {{ \"type\": \"data\", \"bom-ref\": \"asset:{0}\", \"name\": \"{0}\", \"licenses\": {1}, \"properties\": [{{ \"name\": \"iyakki:origin\", \"value\": \"{2}\" }}, {{ \"name\": \"iyakki:status\", \"value\": \"{3}\" }}] }}", esc(&a.path), lic_json(&a.license), esc(&a.origin), esc(&a.status)));
    }
    format!(
        "{{\n  \"bomFormat\": \"CycloneDX\",\n  \"specVersion\": \"1.5\",\n  \"version\": 1,\n  \"metadata\": {{\n    \"tools\": {{ \"components\": [{{ \"type\": \"application\", \"name\": \"iyakki-relcheck\", \"version\": \"{}\" }}] }},\n    \"component\": {{ \"type\": \"application\", \"name\": \"{}\", \"version\": \"{}\", \"licenses\": [{{ \"expression\": \"Apache-2.0\" }}] }}\n  }},\n  \"components\": [\n{}\n  ]\n}}\n",
        esc(version),
        esc(name),
        esc(version),
        comps.join(",\n")
    )
}

fn class_name(c: Class) -> &'static str {
    match c {
        Class::Permissive => "permissive",
        Class::Copyleft => "copyleft",
        Class::Proprietary => "vendor / proprietary",
        Class::Unknown => "unknown",
    }
}

/// `legal/THIRD-PARTY-NOTICES.md`. Licence texts themselves are in `THIRD_PARTY_LICENSES.txt` (cargo-about) and in each image's
/// `legal-info/`; this file is the index that says what is used, under what, and what is only ever downloaded.
pub fn notices(crates: &[Pkg], assets: &[AssetRow], dl: &[downloads::Row]) -> String {
    let mut s = String::from("# Third-party notices\n\nGenerated by `iyakki-relcheck notices` from `Cargo.lock`, `crates/iyakki-gui/Cargo.lock`, `legal/assets.txt` and `legal/downloads.txt`. Do not edit by hand; run `./run.sh licence-check --write`. IYAKKI itself is Apache-2.0 (`LICENSE`, `NOTICE`). Full licence texts of the Rust dependencies: `THIRD_PARTY_LICENSES.txt`. Operating-system packages of an image: that image's `legal-info/` (manifest, licence texts, corresponding source).\n\n");
    let mut by: BTreeMap<String, Vec<String>> = BTreeMap::new();
    let mut seen = std::collections::BTreeSet::new();
    for p in crates.iter().filter(|p| !p.source.is_empty()) {
        if seen.insert((p.name.clone(), p.version.clone())) {
            by.entry(p.license.clone()).or_default().push(format!("{} {}", p.name, p.version));
        }
    }
    s.push_str(&format!("## Rust dependencies ({} crates from crates.io)\n\n| Licence as stated by the crate | Crates |\n|---|---|\n", seen.len()));
    for (l, mut v) in by {
        v.sort();
        let shown = if v.len() > 12 { format!("{} ... and {} more", v[..12].join(", "), v.len() - 12) } else { v.join(", ") };
        s.push_str(&format!("| {} | {} |\n", if l.is_empty() { "(none stated)".into() } else { l.replace('|', "/") }, shown));
    }
    s.push_str("\n## Fonts, icons, pictures, sounds and other data in the repository\n\n| Files | Licence | Origin | Checked |\n|---|---|---|---|\n");
    for a in assets {
        s.push_str(&format!("| `{}` | {} | {} | {} ({}) |\n", a.path, a.license.replace('|', "/"), a.origin.replace('|', "/"), a.status, a.date));
    }
    s.push_str("\n## Downloaded at the person's click, never shipped\n\n| Item | Licence | How it is pinned |\n|---|---|---|\n");
    for d in dl {
        s.push_str(&format!("| {} | {} ({}) | {}: {} |\n", d.id, d.license.replace('|', "/"), class_name(spdx::classify_list(&d.license.replace(" OR ", ", ").replace(" AND ", ", ")).0), d.pin_kind, d.pin.replace('|', "/")));
    }
    s
}

#[cfg(test)]
mod tests {
    use super::*;

    fn p(n: &str, l: &str, o: &str) -> Pkg {
        Pkg { name: n.into(), version: "1.0".into(), license: l.into(), source: "registry+x".into(), sha256: "ab".into(), origin: o.into() }
    }

    #[test]
    fn cyclonedx_is_deterministic_and_escaped() {
        let pk = vec![p("b\"q", "MIT OR Apache-2.0", "cargo:Cargo.lock"), p("busybox", "GPL-2.0, bzip2-1.0.4", "buildroot"), p("b\"q", "MIT OR Apache-2.0", "cargo:crates/iyakki-gui/Cargo.lock")];
        let a = AssetRow { path: "x/logo.png".into(), license: "Apache-2.0".into(), origin: "ours".into(), status: "verified".into(), date: "2026-10-26".into(), image_paths: vec![] };
        let j = cyclonedx("IYAKKI", "0.1.0", &pk, &[a.clone()]);
        assert_eq!(j, cyclonedx("IYAKKI", "0.1.0", &pk, &[a]));
        assert!(j.contains("\"bomFormat\": \"CycloneDX\"") && j.contains("b\\\"q") && j.contains("\"expression\": \"MIT OR Apache-2.0\"") && j.contains("\"name\": \"GPL-2.0, bzip2-1.0.4\"") && j.contains("asset:x/logo.png"));
        assert_eq!(j.matches("pkg:cargo/b").count(), 2 /* bom-ref and purl of one deduplicated component */);
        assert_eq!(j.matches('{').count(), j.matches('}').count());
    }

    #[test]
    fn notices_list_crates_assets_and_downloads() {
        let a = AssetRow { path: "x/*.ttf".into(), license: "OFL-1.1".into(), origin: "Noto".into(), status: "verified".into(), date: "2026-10-26".into(), image_paths: vec![] };
        let (d, _) = downloads::parse("graph-db | GPL-3.0-only | download-only | digest | sha256:aa | reason reason reason | 2026-10-26\n");
        let t = notices(&[p("serde", "MIT OR Apache-2.0", "cargo:Cargo.lock")], &[a], &d);
        assert!(t.contains("| MIT OR Apache-2.0 | serde 1.0 |") && t.contains("`x/*.ttf`") && t.contains("graph-db | GPL-3.0-only (copyleft)"));
    }
}
