//! A simple SBOM (SPDX-lite JSON) from the Cargo lock files and, when a build left one, Buildroot's `legal-info/manifest.csv`,
//! and the list of components whose licence is not purely permissive.

use std::path::{Path, PathBuf};

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Pkg {
    pub name: String,
    pub version: String,
    /// SPDX expression as the crate or package states it; empty when unknown.
    pub license: String,
    pub source: String,
    pub sha256: String,
    /// Which list it came from: `cargo:<lockfile>` or `buildroot`.
    pub origin: String,
}

/// The `[[package]]` entries of a Cargo.lock.
pub fn parse_lock(lock: &str, origin: &str) -> Vec<Pkg> {
    let mut out = Vec::new();
    for block in lock.split("[[package]]").skip(1) {
        let get = |k: &str| block.lines().find_map(|l| l.strip_prefix(&format!("{k} = ")).map(|v| v.trim().trim_matches('"').to_string())).unwrap_or_default();
        let (name, version) = (get("name"), get("version"));
        if name.is_empty() {
            continue;
        }
        out.push(Pkg { name, version, license: String::new(), source: get("source"), sha256: get("checksum"), origin: origin.to_string() });
    }
    out
}

/// `license = "..."` from a crate's Cargo.toml.
pub fn manifest_license(toml: &str) -> Option<String> {
    let mut in_pkg = false;
    for l in toml.lines() {
        let t = l.trim();
        if t.starts_with('[') {
            in_pkg = t == "[package]";
        } else if in_pkg {
            if let Some(v) = t.strip_prefix("license") {
                let v = v.trim_start();
                if let Some(v) = v.strip_prefix('=') {
                    return Some(v.trim().trim_matches('"').to_string());
                }
            }
        }
    }
    None
}

/// Fill in licences from the local cargo registry (`~/.cargo/registry/src/*/<name>-<version>/Cargo.toml`); crates of this
/// repository are Apache-2.0.
pub fn fill_licenses(pkgs: &mut [Pkg], registry_src: &[PathBuf]) {
    for p in pkgs.iter_mut() {
        if p.source.is_empty() {
            p.license = "Apache-2.0".into();
            continue;
        }
        for r in registry_src {
            if let Ok(t) = std::fs::read_to_string(r.join(format!("{}-{}", p.name, p.version)).join("Cargo.toml")) {
                if let Some(l) = manifest_license(&t) {
                    p.license = l;
                    break;
                }
            }
        }
    }
}

fn csv_fields(line: &str) -> Vec<String> {
    let mut out = Vec::new();
    let (mut cur, mut quoted) = (String::new(), false);
    for c in line.chars() {
        match c {
            '"' => quoted = !quoted,
            ',' if !quoted => out.push(std::mem::take(&mut cur)),
            _ => cur.push(c),
        }
    }
    out.push(cur);
    out
}

/// Buildroot's legal-info manifest: PACKAGE, VERSION, LICENSE, ..., SOURCE SITE.
pub fn parse_buildroot_manifest(csv: &str) -> Vec<Pkg> {
    csv.lines().skip(1).map(csv_fields).filter(|f| f.len() >= 6 && !f[0].is_empty()).map(|f| Pkg { name: f[0].clone(), version: f[1].clone(), license: f[2].clone(), source: f[5].clone(), sha256: String::new(), origin: "buildroot".into() }).collect()
}

/// Is the licence expression something other than purely permissive? A crate under `MIT OR LGPL-3.0` can be used under MIT, but is
/// still listed (the owner should know the alternative exists); `purely_copyleft` tells those apart.
pub fn non_permissive(license: &str) -> bool {
    let l = license.to_uppercase();
    ["GPL", "MPL", "EPL", "CDDL", "OFL", "UBUNTU-FONT", "CC-BY", "SSPL", "UNKNOWN", "PROPRIETARY"].iter().any(|k| l.contains(k))
}

/// True when every alternative of an `OR` expression is non-permissive (so there is no permissive way to use it).
pub fn purely_copyleft(license: &str) -> bool {
    let upper = license.to_uppercase();
    let alts: Vec<&str> = upper.split(" OR ").collect();
    alts.iter().all(|a| non_permissive(a))
}

fn esc(s: &str) -> String {
    let mut o = String::new();
    for c in s.chars() {
        match c {
            '"' => o.push_str("\\\""),
            '\\' => o.push_str("\\\\"),
            '\n' => o.push_str("\\n"),
            c if (c as u32) < 0x20 => o.push(' '),
            c => o.push(c),
        }
    }
    o
}

/// SPDX-lite JSON. `created` is `YYYY-MM-DD`.
pub fn to_json(name: &str, version: &str, created: &str, pkgs: &[Pkg]) -> String {
    let mut s = String::new();
    s.push_str(&format!("{{\n  \"spdxVersion\": \"SPDX-2.3\",\n  \"dataLicense\": \"CC0-1.0\",\n  \"name\": \"{}\",\n  \"documentNamespace\": \"https://example.invalid/spdx/{}-{}\",\n  \"comment\": \"SPDX-lite generated by iyakki-relcheck from Cargo.lock files and Buildroot legal-info; licences are as the packages state them, not legal advice.\",\n  \"creationInfo\": {{ \"created\": \"{}\", \"creators\": [\"Tool: iyakki-relcheck-{}\"] }},\n  \"packages\": [\n", esc(name), esc(name), esc(version), esc(created), esc(version)));
    for (i, p) in pkgs.iter().enumerate() {
        let lic = if p.license.is_empty() { "NOASSERTION".to_string() } else { esc(&p.license) };
        // a local path (a package inside this repository) would publish the builder's home folder: say nothing instead
        let dl = if p.source.is_empty() || p.source.starts_with('/') { "NOASSERTION".to_string() } else { esc(&p.source) };
        s.push_str(&format!("    {{ \"SPDXID\": \"SPDXRef-{}-{}\", \"name\": \"{}\", \"versionInfo\": \"{}\", \"downloadLocation\": \"{}\", \"licenseConcluded\": \"{}\", \"supplier\": \"{}\"", i, esc(&p.origin.replace([':', '/', '.'], "-")), esc(&p.name), esc(&p.version), dl, lic, esc(&p.origin)));
        if !p.sha256.is_empty() {
            s.push_str(&format!(", \"checksums\": [{{ \"algorithm\": \"SHA256\", \"checksumValue\": \"{}\" }}]", esc(&p.sha256)));
        }
        s.push_str(" }");
        s.push_str(if i + 1 == pkgs.len() { "\n" } else { ",\n" });
    }
    s.push_str("  ]\n}\n");
    s
}

/// Everything for a repository: both lock files (with licences from the local registry) and the Buildroot manifests that exist.
pub fn collect(root: &Path, registry_src: &[PathBuf]) -> Vec<Pkg> {
    let mut all = Vec::new();
    for lock in ["Cargo.lock", "crates/iyakki-gui/Cargo.lock"] {
        if let Ok(t) = std::fs::read_to_string(root.join(lock)) {
            let mut v = parse_lock(&t, &format!("cargo:{lock}"));
            fill_licenses(&mut v, registry_src);
            all.extend(v);
        }
    }
    for dir in ["buildroot-libre", "buildroot-libre-aarch64", "buildroot-web"] {
        if let Ok(t) = std::fs::read_to_string(root.join("target").join(dir).join("legal-info/manifest.csv")) {
            let mut v = parse_buildroot_manifest(&t);
            v.iter_mut().for_each(|p| p.origin = format!("buildroot:{dir}"));
            all.extend(v);
        }
    }
    all
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn lock_and_manifest_parse() {
        let lock = "[[package]]\nname = \"iyakki-sec\"\nversion = \"0.1.0\"\n\n[[package]]\nname = \"serde\"\nversion = \"1.0.1\"\nsource = \"registry+https://github.com/rust-lang/crates.io-index\"\nchecksum = \"abc\"\n";
        let p = parse_lock(lock, "cargo:Cargo.lock");
        assert_eq!(p.len(), 2);
        assert_eq!(p[1].sha256, "abc");
        assert!(p[0].source.is_empty());
        assert_eq!(manifest_license("[package]\nname=\"x\"\nlicense = \"MIT OR Apache-2.0\"\n").as_deref(), Some("MIT OR Apache-2.0"));
        let csv = "\"PACKAGE\",\"VERSION\",\"LICENSE\",\"LICENSE FILES\",\"SOURCE ARCHIVE\",\"SOURCE SITE\",\"DEPS\"\n\"musl\",\"1.2.6\",\"MIT\",\"COPYRIGHT\",\"musl.tar.gz\",\"http://musl.libc.org\",\"a, b\"\n";
        let b = parse_buildroot_manifest(csv);
        assert_eq!((b[0].name.as_str(), b[0].license.as_str(), b[0].source.as_str()), ("musl", "MIT", "http://musl.libc.org"));
    }

    #[test]
    fn licence_classes() {
        assert!(!non_permissive("MIT OR Apache-2.0"));
        assert!(non_permissive("MIT OR LGPL-3.0-or-later"));
        assert!(!purely_copyleft("MIT OR LGPL-3.0-or-later"));
        assert!(purely_copyleft("GPL-2.0-only"));
        assert!(non_permissive("MPL-2.0") && non_permissive("OFL-1.1 AND Ubuntu-font-1.0"));
    }

    #[test]
    fn json_is_valid_looking_and_escaped() {
        let p = vec![Pkg { name: "a\"b".into(), version: "1".into(), license: String::new(), source: String::new(), sha256: "ff".into(), origin: "cargo:Cargo.lock".into() }];
        let j = to_json("IYAKKI", "0.1.0-alpha.1", "2026-10-17", &p);
        assert!(j.contains("\"spdxVersion\": \"SPDX-2.3\"") && j.contains("a\\\"b") && j.contains("NOASSERTION") && j.contains("\"checksumValue\": \"ff\""));
        assert_eq!(j.matches('{').count(), j.matches('}').count());
    }

    #[test]
    fn local_paths_never_reach_the_sbom() {
        let p = vec![Pkg { name: "helper".into(), version: "1".into(), license: "Apache-2.0".into(), source: "/home/someone/src/helper".into(), sha256: String::new(), origin: "buildroot:web".into() }];
        let j = to_json("IYAKKI", "0.1.0-alpha.1", "2026-10-18", &p);
        assert!(!j.contains("/home/") && j.contains("\"downloadLocation\": \"NOASSERTION\""));
    }

    #[test]
    fn licences_come_from_the_registry() {
        let d = std::env::temp_dir().join(format!("iyakki-relcheck-sbom-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&d);
        std::fs::create_dir_all(d.join("serde-1.0.1")).unwrap();
        std::fs::write(d.join("serde-1.0.1/Cargo.toml"), "[package]\nlicense = \"MIT\"\n").unwrap();
        let mut p = parse_lock("[[package]]\nname = \"serde\"\nversion = \"1.0.1\"\nsource = \"registry+x\"\n\n[[package]]\nname = \"iyakki-a\"\nversion = \"1\"\n", "x");
        fill_licenses(&mut p, &[d.clone()]);
        assert_eq!((p[0].license.as_str(), p[1].license.as_str()), ("MIT", "Apache-2.0"));
        let _ = std::fs::remove_dir_all(&d);
    }
}
